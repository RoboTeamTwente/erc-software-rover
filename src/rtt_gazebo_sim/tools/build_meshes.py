#!/usr/bin/env python3
"""Turn the ERC 2026 Mars Yard scan into Gazebo-ready meshes.

Inputs : Model3D_mesh2.obj   (Meshlab export, per-vertex colour, no UVs, Z-up,
                              same local frame as Coordinates_MarsYard2026.txt)
         orthophoto.tif      (GeoTIFF, 1 cm/px, same local frame)
Outputs: <out>/meshes/erc2026_visual.obj + .mtl   (decimated, planar UVs onto orthophoto)
         <out>/meshes/erc2026_collision.obj       (heavily decimated, for physics)
         <out>/meshes/textures/erc2026_orthophoto.jpg

Decimation is plain vertex clustering (numpy only, no extra packages).

usage: build_meshes.py MESH_OBJ ORTHO_TIF OUT_DIR [--visual-cell 0.06] [--collision-cell 0.20]
"""
import argparse
import os

import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None


def load_obj(path):
    V, F = [], []
    with open(path) as fh:
        for line in fh:
            if line.startswith("v "):
                V.append(line[2:])
            elif line.startswith("f "):
                F.append(line[2:].replace("//", " "))
    V = np.array(" ".join(V).split(), dtype=np.float64).reshape(-1, 6)[:, :3]
    F = np.array(" ".join(F).split(), dtype=np.int64).reshape(-1, 6)[:, ::2] - 1
    return V, F


def cluster(V, F, cell):
    """Vertex-clustering decimation on a cubic grid of size `cell` metres."""
    q = np.floor((V - V.min(0)) / cell).astype(np.int64)
    dims = q.max(0) + 1
    key = (q[:, 0] * dims[1] + q[:, 1]) * dims[2] + q[:, 2]
    _, inv, counts = np.unique(key, return_inverse=True, return_counts=True)
    newV = np.stack([np.bincount(inv, V[:, i]) for i in range(3)], 1) / counts[:, None]
    nf = inv[F]
    keep = (nf[:, 0] != nf[:, 1]) & (nf[:, 1] != nf[:, 2]) & (nf[:, 0] != nf[:, 2])
    nf = nf[keep]
    _, first = np.unique(np.sort(nf, 1), axis=0, return_index=True)
    nf = nf[np.sort(first)]
    used = np.unique(nf)
    remap = -np.ones(len(newV), np.int64)
    remap[used] = np.arange(len(used))
    return newV[used], remap[nf]


def vertex_normals(V, F):
    fn = np.cross(V[F[:, 1]] - V[F[:, 0]], V[F[:, 2]] - V[F[:, 0]])  # area-weighted
    N = np.zeros_like(V)
    for i in range(3):
        np.add.at(N, F[:, i], fn)
    N /= np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-12)
    return N


def geotiff_extent(tif):
    """Return (x_left, y_top, width_m, height_m) from ModelTiepoint/ModelPixelScale tags."""
    im = Image.open(tif)
    tp = im.tag_v2[33922]  # (i, j, k, x, y, z)
    sc = im.tag_v2[33550]  # (sx, sy, sz)
    w, h = im.size
    assert tp[0] == 0 and tp[1] == 0, "expected tiepoint at pixel (0,0)"
    return tp[3], tp[4], w * sc[0], h * sc[1]


def write_obj(path, V, F, N=None, UV=None, mtl=None, material=None):
    with open(path, "w") as fh:
        fh.write("# ERC 2026 Mars Yard terrain, generated by build_meshes.py\n")
        if mtl:
            fh.write(f"mtllib {mtl}\n")
        np.savetxt(fh, V, fmt="v %.4f %.4f %.4f")
        if UV is not None:
            np.savetxt(fh, UV, fmt="vt %.5f %.5f")
        if N is not None:
            np.savetxt(fh, N, fmt="vn %.3f %.3f %.3f")
        if material:
            fh.write(f"usemtl {material}\n")
        f1 = F + 1
        if UV is not None and N is not None:
            fmt = "f %d/%d/%d %d/%d/%d %d/%d/%d"
            np.savetxt(fh, np.repeat(f1, 3, axis=1), fmt=fmt)
        elif N is not None:
            np.savetxt(fh, np.repeat(f1, 2, axis=1), fmt="f %d//%d %d//%d %d//%d")
        else:
            np.savetxt(fh, f1, fmt="f %d %d %d")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mesh")
    ap.add_argument("ortho")
    ap.add_argument("out")
    ap.add_argument("--visual-cell", type=float, default=0.06)
    ap.add_argument("--collision-cell", type=float, default=0.20)
    a = ap.parse_args()

    os.makedirs(f"{a.out}/meshes", exist_ok=True)
    os.makedirs(f"{a.out}/meshes/textures", exist_ok=True)

    V, F = load_obj(a.mesh)
    print(f"input: {len(V)} verts, {len(F)} faces")

    # --- texture: orthophoto -> RGB JPEG (transparent border becomes neutral sand colour)
    x0, y_top, wm, hm = geotiff_extent(a.ortho)
    im = Image.open(a.ortho).convert("RGBA")
    rgba = np.asarray(im)
    rgb = rgba[..., :3].copy()
    opaque = rgba[..., 3] > 0
    fill = np.median(rgb[opaque], axis=0).astype(np.uint8)
    rgb[~opaque] = fill
    Image.fromarray(rgb).save(f"{a.out}/meshes/textures/erc2026_orthophoto.jpg", quality=90)
    print(f"texture: {im.size}, extent x[{x0:.3f},{x0 + wm:.3f}] y[{y_top - hm:.3f},{y_top:.3f}], "
          f"{100 * (~opaque).mean():.1f}% transparent px filled")

    # --- visual mesh
    Vv, Fv = cluster(V, F, a.visual_cell)
    Nv = vertex_normals(Vv, Fv)
    UV = np.c_[(Vv[:, 0] - x0) / wm, (Vv[:, 1] - (y_top - hm)) / hm]  # OBJ: v=0 at image bottom
    UV = np.clip(UV, 0.0, 1.0)
    with open(f"{a.out}/meshes/erc2026_visual.mtl", "w") as fh:
        fh.write("newmtl erc2026_ground\n"
                 "Ka 1.0 1.0 1.0\nKd 1.0 1.0 1.0\nKs 0.0 0.0 0.0\nNs 1.0\nd 1.0\nillum 1\n"
                 "map_Kd textures/erc2026_orthophoto.jpg\n")
    write_obj(f"{a.out}/meshes/erc2026_visual.obj", Vv, Fv, Nv, UV,
              mtl="erc2026_visual.mtl", material="erc2026_ground")
    print(f"visual   (cell {a.visual_cell} m): {len(Vv)} verts, {len(Fv)} faces")

    # --- collision mesh
    Vc, Fc = cluster(V, F, a.collision_cell)
    # normals included: DART was reported to crash on a normal-less terrain OBJ (rtt_gazebo_sim)
    write_obj(f"{a.out}/meshes/erc2026_collision.obj", Vc, Fc, vertex_normals(Vc, Fc))
    print(f"collision(cell {a.collision_cell} m): {len(Vc)} verts, {len(Fc)} faces")


if __name__ == "__main__":
    main()
